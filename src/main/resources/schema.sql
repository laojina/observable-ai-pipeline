CREATE TABLE IF NOT EXISTS tasks (
  id VARCHAR(36) PRIMARY KEY, asset VARCHAR(200) NOT NULL, revision VARCHAR(80) NOT NULL,
  status VARCHAR(30) NOT NULL, duration_ms BIGINT NOT NULL, fail_step INT NOT NULL,
  fail_times INT NOT NULL, timeout_ms BIGINT NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS steps (
  task_id VARCHAR(36) NOT NULL REFERENCES tasks(id), position INT NOT NULL, name VARCHAR(40) NOT NULL,
  status VARCHAR(30) NOT NULL, attempts INT NOT NULL DEFAULT 0, max_attempts INT NOT NULL DEFAULT 3,
  next_run_at BIGINT NOT NULL DEFAULT 0, heartbeat BIGINT, error VARCHAR(1000),
  artifact VARCHAR(500), artifact_hash VARCHAR(64), fingerprint VARCHAR(64),
  PRIMARY KEY(task_id, position)
);
CREATE TABLE IF NOT EXISTS attempts (
  id VARCHAR(36) PRIMARY KEY, task_id VARCHAR(36) NOT NULL, position INT NOT NULL,
  attempt_no INT NOT NULL, status VARCHAR(30) NOT NULL, started_at BIGINT NOT NULL,
  ended_at BIGINT, error VARCHAR(1000)
);
CREATE TABLE IF NOT EXISTS events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, task_id VARCHAR(36) NOT NULL,
  recorded_at BIGINT NOT NULL, message VARCHAR(1000) NOT NULL
);
